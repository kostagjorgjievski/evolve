# --- Test 3: an existing cache is never replaced ----------------------------------------


def test_an_existing_cache_is_never_replaced(env: SimpleNamespace) -> None:
    """A second build refuses, naming the existing cache id, and touches no file."""
    _build(env)
    ident = foundation_cache_id(env.root, "etth1", "fake")
    base = env.root / "etth1" / "fake"
    files = [base / "manifest.json", *sorted((base / "series").glob("*.f64"))]
    before = {file: (file.read_bytes(), file.stat().st_mtime_ns) for file in files}
    with pytest.raises(FoundationError, match="already exists") as excinfo:
        _build(env)
    assert ident in str(excinfo.value)
    assert {file: (file.read_bytes(), file.stat().st_mtime_ns) for file in files} == before
    assert sorted(p.name for p in (env.root / "etth1").iterdir()) == ["fake"]


# --- Tests 4 and 5: resume --------------------------------------------------------------


def test_resume_after_a_crash_reuses_completed_series(env: SimpleNamespace) -> None:
    """A rerun keeps the completed files, skips their adapter calls, and finishes the build."""
    with pytest.raises(RuntimeError, match="simulated crash"):
        _build(env, adapter=_CrashAfter(limit=2), batch_size=1000)  # one adapter call per series
    partials = list((env.root / "etth1").glob(".fake.partial-*"))
    assert len(partials) == 1
    partial = partials[0]
    assert sorted(p.name for p in (partial / "series").iterdir()) == ["0000.f64", "0001.f64"]
    reused_mtime = (partial / "series" / "0000.f64").stat().st_mtime_ns

    counting = _Counting()
    resumed = _build(env, adapter=counting, batch_size=1000)
    assert counting.calls == _N_SERIES - 2  # only the series the crash never finished
    assert (env.root / "etth1" / "fake" / "series" / "0000.f64").stat().st_mtime_ns == reused_mtime
    assert sorted(p.name for p in (env.root / "etth1").iterdir()) == ["fake"]
    assert sorted(p.name for p in (env.root / "etth1" / "fake" / "series").iterdir()) == [
        f"{i:04d}.f64" for i in range(_N_SERIES)
    ]

    fresh = _build(env, adapter=FakeAdapter(), root=env.root2, batch_size=1000)
    assert dataclasses.replace(resumed, build_seconds=0.0) == dataclasses.replace(
        fresh, build_seconds=0.0
    )
    # build_seconds is the only difference, so the two builds have different cache ids.
    assert foundation_cache_id(env.root, "etth1", "fake") != foundation_cache_id(
        env.root2, "etth1", "fake"
    )


def test_a_truncated_series_file_in_the_partial_directory_is_rewritten(
    env: SimpleNamespace,
) -> None:
    """A right-name, wrong-size file from a crash mid-write is recomputed, not kept."""
    with pytest.raises(RuntimeError, match="simulated crash"):
        _build(env, adapter=_CrashAfter(limit=2), batch_size=1000)
    partial = next((env.root / "etth1").glob(".fake.partial-*"))
    raw = (partial / "series" / "0000.f64").read_bytes()
    (partial / "series" / "0000.f64").write_bytes(raw[: len(raw) // 2])

    counting = _Counting()
    manifest = _build(env, adapter=counting, batch_size=1000)
    assert counting.calls == _N_SERIES - 1  # the truncated series plus the never-started ones
    rewritten = env.root / "etth1" / "fake" / "series" / "0000.f64"
    assert rewritten.stat().st_size == _N_ORIGINS * len(QUANTILES) * _HORIZON * 8
    fresh = _build(env, adapter=FakeAdapter(), root=env.root2, batch_size=1000)
    assert manifest.series[0].sha256 == fresh.series[0].sha256  # rewritten from scratch
    assert verify_foundation_cache(env.root, "etth1", "fake") == manifest


# --- Test 6: verify catches tampering ---------------------------------------------------


def test_verify_catches_tampered_series_files(env: SimpleNamespace) -> None:
    """A flipped byte, a truncated file and a missing file each raise, naming the file."""
    _build(env)
    path = env.root / "etth1" / "fake" / "series" / "0000.f64"
    raw = path.read_bytes()

    path.write_bytes(raw[:-1] + bytes([raw[-1] ^ 0xFF]))
    with pytest.raises(FoundationError, match=r"series/0000\.f64: sha256"):
        verify_foundation_cache(env.root, "etth1", "fake")

    path.write_bytes(raw[:-8])
    with pytest.raises(FoundationError, match=r"series/0000\.f64: expected"):
        verify_foundation_cache(env.root, "etth1", "fake")

    path.unlink()
    with pytest.raises(FoundationError, match=r"series/0000\.f64: cannot be read"):
        verify_foundation_cache(env.root, "etth1", "fake")

    path.write_bytes(raw)
    assert verify_foundation_cache(env.root, "etth1", "fake").model.name == "fake"


