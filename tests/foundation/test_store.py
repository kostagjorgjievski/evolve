def _build(
    env: SimpleNamespace,
    adapter: FakeAdapter | None = None,
    root: Path | None = None,
    batch_size: int = _BATCH,
) -> FoundationManifest:
    """Build the fixture foundation cache (etth1/fake) under ``root`` (default ``env.root``)."""
    return build_foundation_cache(
        "etth1",
        adapter if adapter is not None else FakeAdapter(),
        FAKE_SPEC,
        env.root if root is None else root,
        env.cache_root,
        env.data_root,
        env.manifest_dir,
        batch_size,
    )


class _NeverCalled(FakeAdapter):
    """A FakeAdapter that fails the test if the builder ever calls it."""

    def forecast(self, contexts, horizon):
        raise AssertionError("the adapter must not be called for these inputs")


class _CrashAfter(FakeAdapter):
    """A FakeAdapter that raises once it has served ``limit`` forecast calls."""

    def __init__(self, limit: int) -> None:
        super().__init__()
        self._limit = limit
        self.calls = 0

    def forecast(self, contexts, horizon):
        self.calls += 1
        if self.calls > self._limit:
            raise RuntimeError("simulated crash")
        return super().forecast(contexts, horizon)


class _Counting(FakeAdapter):
    """A FakeAdapter that counts its forecast calls."""

    def __init__(self) -> None:
        super().__init__()
        self.calls = 0

    def forecast(self, contexts, horizon):
        self.calls += 1
        return super().forecast(contexts, horizon)


# --- Test 1: build, verify, load --------------------------------------------------------


def test_build_verify_load_round_trip(env: SimpleNamespace) -> None:
    """Loaded values equal forecast_series output, and point() is the 0.5-quantile row."""
    manifest = _build(env)
    assert verify_foundation_cache(env.root, "etth1", "fake") == manifest
    base = env.root / "etth1" / "fake"
    assert sorted(p.name for p in base.iterdir()) == ["manifest.json", "series"]
    assert sorted(p.name for p in (base / "series").iterdir()) == [
        f"{i:04d}.f64" for i in range(_N_SERIES)
    ]
    for entry, series in zip(manifest.series, env.series, strict=True):
        loaded = load_foundation_series(env.root, manifest, entry.series_id)
        expected = forecast_series(
            FakeAdapter(), series.values, _START, FAKE_SPEC.max_context, _HORIZON, _BATCH
        )
        assert loaded.series_id == entry.series_id
        assert (loaded.first_origin, loaded.n_origins, loaded.last_origin) == (
            _START,
            _N_ORIGINS,
            _ROWS - 1,
        )
        assert loaded.sorted_steps == 0  # the fake's output is monotone in the quantile level
        assert [loaded.row(i) for i in range(_N_ORIGINS)] == list(expected.values)
        for i in range(_N_ORIGINS):
            assert loaded.point(i) == expected.values[i][_POINT]
            assert loaded.point(i) == loaded.row(i)[_POINT]
    with pytest.raises(FoundationError, match="unknown series_id"):
        load_foundation_series(env.root, manifest, "fixture/missing")
    loaded = load_foundation_series(env.root, manifest, manifest.series[0].series_id)
    for bad in (-1, _N_ORIGINS):
        with pytest.raises(FoundationError, match="outside"):
            loaded.point(bad)
    with pytest.raises(FoundationError, match="must be an int"):
        loaded.point(True)


