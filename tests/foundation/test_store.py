_START = first_origin(_PERIOD)  # 287
_HORIZON = DEFAULT_HORIZON  # 24
_ROWS = 344  # the fixture's public rows (its sealed segment start)
_N_SERIES = 7
_N_ORIGINS = _ROWS - _START  # 57 per series
