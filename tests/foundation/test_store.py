def test_inputs_differing_from_the_simple_cache_are_refused_before_any_adapter_call(
    env: SimpleNamespace, tmp_path: Path
) -> None:
    """A changed value or origin range is refused before the adapter is called once."""
    first = env.series[0]
    cases = {
        "values": (
            SeriesInput(first.series_id, (*first.values[:-1], 999.0), _PERIOD),
            *env.series[1:],
        ),
        "origins": (SeriesInput(first.series_id, first.values[:-1], _PERIOD), *env.series[1:]),
    }
    for label, series in cases.items():
        cache_root = tmp_path / f"cache_{label}"
        build_cache("etth1", env.source, series, cache_root)
        with pytest.raises(FoundationError, match="does not match the simple cache"):
            build_foundation_cache(
                "etth1",
                _NeverCalled(),
                FAKE_SPEC,
                env.root,
                cache_root,
                env.data_root,
                env.manifest_dir,
                _BATCH,
            )
        assert not (env.root / "etth1").exists()


