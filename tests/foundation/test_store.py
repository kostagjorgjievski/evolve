def test_tampered_manifests_are_refused(env: SimpleNamespace) -> None:
    """Structural faults and unknown versions are refused on read, not reinterpreted."""
    _build(env)
    path = env.root / "etth1" / "fake" / "manifest.json"
    original = json.loads(path.read_bytes())

    def tamper(mutate: dict, label: str) -> None:
        path.write_text(json.dumps(mutate), encoding="utf-8")
        with pytest.raises(FoundationError, match=label):
            read_foundation_manifest(env.root, "etth1", "fake")

    tamper({**original, "foundation_cache_version": "3"}, "refused")
    tamper({k: v for k, v in original.items() if k != "dtype"}, "keys must be exactly")
    tamper(
        {**original, "quantiles": [0.1, 0.2, 0.3, 0.4, 0.55, 0.6, 0.7, 0.8, 0.9]},
        "quantiles must be",
    )
    tamper({**original, "batch_size": 0}, "batch_size must be >= 1")
    tamper({**original, "build_seconds": -1.0}, "build_seconds must be")
    tamper({**original, "simple_cache_id": "not-hex"}, "64 lowercase hex")
    tamper({**original, "model": {**original["model"], "name": "chronos2"}}, "model name must be")
    tamper({**original, "model": {**original["model"], "extra": 1}}, "keys must be exactly")
    tampered_series = [
        dict(original["series"][0], n_origins=original["series"][0]["n_origins"] + 1),
        *original["series"][1:],
    ]
    tamper({**original, "series": tampered_series}, "length - first_origin")


